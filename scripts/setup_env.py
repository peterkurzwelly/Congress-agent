"""Interactive CLI to create or update a .env file for Congress Trades.

Prompts for each API key / credential with descriptions, then writes
(or merges into an existing) .env file.  Existing values are preserved
unless the user explicitly replaces them.

Usage:
    uv run python scripts/setup_env.py
    uv run python scripts/setup_env.py --env-file /path/to/.env
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

# ---------------------------------------------------------------------------
# Helpers
# ---------------------------------------------------------------------------


def _load_existing_env(path: Path) -> dict[str, str]:
    """Parse an existing .env file into a {KEY: raw_value} dict.

    Handles quoted values and skips comments / blank lines.
    """
    env: dict[str, str] = {}
    if not path.exists():
        return env

    for line in path.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        if "=" not in line:
            continue
        key, _, value = line.partition("=")
        key = key.strip()
        value = value.strip()
        # Strip surrounding quotes if present
        if len(value) >= 2 and value[0] == value[-1] and value[0] in ('"', "'"):
            value = value[1:-1]
        env[key] = value

    return env


def _prompt(
    label: str,
    description: str,
    current: str = "",
    *,
    secret: bool = False,
    optional: bool = True,
) -> str:
    """Prompt the user for a value, showing the current value if one exists.

    Parameters
    ----------
    label:
        The environment variable name.
    description:
        Human-readable explanation shown before the prompt.
    current:
        The existing value (shown as placeholder, kept if user presses Enter).
    secret:
        If True, mask the displayed current value.
    optional:
        Whether to show "(optional)" hint.

    Returns
    -------
    str
        The new value (or the existing one if the user pressed Enter).
    """
    tag = " (optional)" if optional else " (required)"
    print(f"\n  {label}{tag}")
    print(f"  {description}")

    if current:
        masked = ("*" * min(len(current), 8) + current[-4:]) if secret else current
        print(f"  Current value: {masked}")
        prompt_str = "  New value [keep current]: "
    else:
        prompt_str = "  Value: "

    try:
        value = input(prompt_str).strip()
    except (EOFError, KeyboardInterrupt):
        print()
        return current

    return value if value else current


def _yes_no(question: str, default: bool = False) -> bool:
    """Prompt for a yes/no answer."""
    hint = "[Y/n]" if default else "[y/N]"
    try:
        answer = input(f"\n{question} {hint}: ").strip().lower()
    except (EOFError, KeyboardInterrupt):
        print()
        return default

    if not answer:
        return default
    return answer in ("y", "yes")


def _write_env(path: Path, values: dict[str, str]) -> None:
    """Write the values dict to a .env file, one KEY=VALUE per line."""
    lines: list[str] = [
        "# Congress Trades — environment configuration",
        "# Generated by scripts/setup_env.py",
        "# Do NOT commit this file to version control.",
        "",
    ]

    sections: list[tuple[str, list[str]]] = [
        (
            "API Keys",
            ["ANTHROPIC_API_KEY", "ANTHROPIC_MODEL", "CONGRESS_API_KEY"],
        ),
        (
            "Telegram Alerts",
            ["TELEGRAM_BOT_TOKEN", "TELEGRAM_CHAT_ID"],
        ),
        (
            "Email / SMTP Alerts",
            [
                "ENABLE_EMAIL_ALERTS",
                "SMTP_HOST",
                "SMTP_PORT",
                "SMTP_USERNAME",
                "SMTP_PASSWORD",
                "ALERT_EMAIL_FROM",
                "ALERT_EMAIL_TO",
            ],
        ),
        (
            "Database",
            ["DATABASE_URL"],
        ),
        (
            "Scheduler",
            [
                "ENABLE_SCHEDULER",
                "SCRAPE_INTERVAL_HOURS",
                "SENATE_SCRAPE_INTERVAL_HOURS",
                "REQUEST_DELAY_SECONDS",
            ],
        ),
        (
            "Anomaly & STOCK Act Thresholds",
            [
                "ANOMALY_ALERT_THRESHOLD",
                "LARGE_TRADE_THRESHOLD",
                "STOCK_ACT_DISCLOSURE_DAYS",
            ],
        ),
    ]

    written: set[str] = set()

    for section_name, keys in sections:
        section_lines: list[str] = []
        for key in keys:
            if key in values:
                val = values[key]
                # Quote values that contain spaces or special chars
                if " " in val or "#" in val or not val:
                    val = f'"{val}"'
                section_lines.append(f"{key}={val}")
                written.add(key)
        if section_lines:
            lines.append(f"# --- {section_name} ---")
            lines.extend(section_lines)
            lines.append("")

    # Write any remaining keys not covered by sections
    remainder = [f"{k}={v}" for k, v in values.items() if k not in written]
    if remainder:
        lines.append("# --- Other ---")
        lines.extend(remainder)
        lines.append("")

    path.write_text("\n".join(lines), encoding="utf-8")


