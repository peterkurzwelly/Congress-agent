DEFAULTS: dict[str, str] = {
    "ANTHROPIC_MODEL": "claude-sonnet-4-20250514",
    "DATABASE_URL": "sqlite+aiosqlite:///./congress_trades.db",
    "ENABLE_SCHEDULER": "false",
    "SCRAPE_INTERVAL_HOURS": "6",
    "SENATE_SCRAPE_INTERVAL_HOURS": "4",
    "REQUEST_DELAY_SECONDS": "1.0",
    "ANOMALY_ALERT_THRESHOLD": "50",
    "LARGE_TRADE_THRESHOLD": "100000",
    "STOCK_ACT_DISCLOSURE_DAYS": "45",
    "SMTP_PORT": "587",
    "ENABLE_EMAIL_ALERTS": "false",
}


# ---------------------------------------------------------------------------
# Main interactive flow
# ---------------------------------------------------------------------------


def run_setup(env_path: Path) -> None:
    existing = _load_existing_env(env_path)

    # Seed defaults for keys that don't already exist
    values: dict[str, str] = {**DEFAULTS, **existing}

    action = "Updating" if env_path.exists() else "Creating"
    print(f"\n{'='*60}")
    print("  Congress Trades — Environment Setup")
    print(f"  {action}: {env_path.resolve()}")
    print(f"{'='*60}")
    print("\nPress Enter to keep current values. All fields are optional")
    print("unless noted otherwise.\n")

    # ------------------------------------------------------------------
    # API Keys
    # ------------------------------------------------------------------
    print("\n[1/4] API Keys")
    print("-" * 40)

    values["ANTHROPIC_API_KEY"] = _prompt(
        "ANTHROPIC_API_KEY",
        "Used for AI-assisted PDF parsing of scanned filings.\n"
        "  Get one at: https://console.anthropic.com/",
        current=values.get("ANTHROPIC_API_KEY", ""),
        secret=True,
    )

    values["CONGRESS_API_KEY"] = _prompt(
        "CONGRESS_API_KEY",
        "Used to fetch bill/committee data from api.congress.gov.\n"
        "  Free sign-up at: https://api.congress.gov/sign-up/",
        current=values.get("CONGRESS_API_KEY", ""),
        secret=True,
    )

    # ------------------------------------------------------------------
    # Telegram
    # ------------------------------------------------------------------
    print("\n[2/4] Telegram Alerts")
    print("-" * 40)

    values["TELEGRAM_BOT_TOKEN"] = _prompt(
        "TELEGRAM_BOT_TOKEN",
        "Token for your Telegram bot.\n"
        "  Create one via @BotFather on Telegram (send /newbot).",
        current=values.get("TELEGRAM_BOT_TOKEN", ""),
        secret=True,
    )

    values["TELEGRAM_CHAT_ID"] = _prompt(
        "TELEGRAM_CHAT_ID",
        "Telegram chat/channel ID to receive alerts.\n"
        "  Find it by messaging @userinfobot on Telegram.",
        current=values.get("TELEGRAM_CHAT_ID", ""),
    )

    # ------------------------------------------------------------------
    # Email / SMTP (optional group)
    # ------------------------------------------------------------------
    print("\n[3/4] Email Alerts")
    print("-" * 40)

    want_email = _yes_no(
        "Set up email (SMTP) alerts?",
        default=values.get("ENABLE_EMAIL_ALERTS", "false").lower() == "true",
    )

    if want_email:
        values["ENABLE_EMAIL_ALERTS"] = "true"

        values["SMTP_HOST"] = _prompt(
            "SMTP_HOST",
            "SMTP server hostname (e.g. smtp.gmail.com, smtp.sendgrid.net).",
            current=values.get("SMTP_HOST", ""),
        )

        values["SMTP_PORT"] = _prompt(
            "SMTP_PORT",
            "SMTP server port (default: 587 for STARTTLS, 465 for SSL).",
            current=values.get("SMTP_PORT", "587"),
        )

        values["SMTP_USERNAME"] = _prompt(
            "SMTP_USERNAME",
            "SMTP login username (often the sender email address).",
            current=values.get("SMTP_USERNAME", ""),
        )

        values["SMTP_PASSWORD"] = _prompt(
            "SMTP_PASSWORD",
            "SMTP login password or app-specific password.",
            current=values.get("SMTP_PASSWORD", ""),
            secret=True,
        )

        values["ALERT_EMAIL_FROM"] = _prompt(
            "ALERT_EMAIL_FROM",
            "From address for outgoing alerts (e.g. alerts@yourdomain.com).",
            current=values.get("ALERT_EMAIL_FROM", ""),
        )

        values["ALERT_EMAIL_TO"] = _prompt(
            "ALERT_EMAIL_TO",
            "Comma-separated list of recipient addresses.",
            current=values.get("ALERT_EMAIL_TO", ""),
        )
    else:
        values["ENABLE_EMAIL_ALERTS"] = "false"

    # ------------------------------------------------------------------
    # Advanced / optional overrides
    # ------------------------------------------------------------------
    print("\n[4/4] Advanced Settings (press Enter to keep defaults)")
    print("-" * 40)

    if _yes_no("Customize database URL or scheduler settings?", default=False):
        values["DATABASE_URL"] = _prompt(
            "DATABASE_URL",
            "SQLAlchemy async DB URL.\n"
            "  Default: sqlite+aiosqlite:///./congress_trades.db",
            current=values.get("DATABASE_URL", DEFAULTS["DATABASE_URL"]),
        )

        values["ENABLE_SCHEDULER"] = (
            "true"
            if _yes_no(
                "Enable background scheduler (APScheduler)?",
                default=values.get("ENABLE_SCHEDULER", "false").lower() == "true",
            )
            else "false"
        )

        values["ANOMALY_ALERT_THRESHOLD"] = _prompt(
            "ANOMALY_ALERT_THRESHOLD",
            "Minimum anomaly score (0-100) to trigger an alert (default: 50).",
            current=values.get("ANOMALY_ALERT_THRESHOLD", "50"),
        )

        values["LARGE_TRADE_THRESHOLD"] = _prompt(
            "LARGE_TRADE_THRESHOLD",
            "Minimum trade amount (USD) to flag as a large trade (default: 100000).",
            current=values.get("LARGE_TRADE_THRESHOLD", "100000"),
        )

    # ------------------------------------------------------------------
    # Write
    # ------------------------------------------------------------------
    print()
    _write_env(env_path, values)

    print(f"\n  .env written to: {env_path.resolve()}")
    print("  Run `uv run python scripts/test_alerts.py --telegram` to verify alerts.")
    print()


# ---------------------------------------------------------------------------
# Entry point
# ---------------------------------------------------------------------------


def main() -> None:
    parser = argparse.ArgumentParser(
        description="Interactive setup for the Congress Trades .env file.",
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog=(
            "Examples:\n"
            "  uv run python scripts/setup_env.py\n"
            "  uv run python scripts/setup_env.py --env-file /etc/congress_trades/.env\n"
        ),
    )
    parser.add_argument(
        "--env-file",
        default=".env",
        metavar="PATH",
        help="Path to the .env file to create or update (default: .env)",
    )

    args = parser.parse_args()
    env_path = Path(args.env_file)

    # Refuse to overwrite a non-.env file accidentally
    if env_path.suffix not in (".env", "") and not env_path.name.startswith(".env"):
        print(
            f"ERROR: {env_path} does not look like a .env file. "
            "Pass --env-file explicitly if you are sure.",
            file=sys.stderr,
        )
        sys.exit(1)

    run_setup(env_path)


if __name__ == "__main__":
    main()
